CREATE TABLE users(id TEXT PRIMARY KEY,email TEXT NOT NULL,name TEXT NOT NULL);
CREATE TABLE sessions(id TEXT PRIMARY KEY,user_id TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE oauth_states(id TEXT PRIMARY KEY,verifier TEXT NOT NULL,nonce TEXT NOT NULL,expires INTEGER NOT NULL);
CREATE TABLE characters(id TEXT PRIMARY KEY,owner TEXT NOT NULL,data TEXT NOT NULL,updated INTEGER NOT NULL);
CREATE INDEX characters_owner ON characters(owner);
CREATE TABLE chats(id TEXT PRIMARY KEY,owner TEXT NOT NULL,character_id TEXT NOT NULL,data TEXT NOT NULL,updated INTEGER NOT NULL,locked_until INTEGER NOT NULL DEFAULT 0);
CREATE INDEX chats_owner ON chats(owner);
CREATE TABLE providers(owner TEXT NOT NULL,id TEXT NOT NULL,model TEXT NOT NULL,secret TEXT,hidden INTEGER NOT NULL DEFAULT 0,PRIMARY KEY(owner,id));
